using CareService.Application.DTOs.Prescriptions;
using CareService.Application.Interfaces;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;


namespace CareService.Infrastructure.Pdf;

public class QuestPdfPrescriptionGenerator
    : IPrescriptionPdfGenerator
{
    public byte[] Generate(PrescriptionPdfDto prescription)
    {
        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(35);
                page.DefaultTextStyle(x => x.FontSize(10));

                page.Header()
                    .Column(column =>
                    {
                        column.Item()
                            .Text("CAREBRIDGE")
                            .FontSize(24)
                            .Bold()
                            .FontColor(Colors.Blue.Medium);

                        column.Item()
                            .Text("Medical Prescription")
                            .FontSize(16)
                            .Bold();

                        column.Item()
                            .LineHorizontal(1);
                    });

                page.Content()
                    .PaddingVertical(15)
                    .Column(column =>
                    {
                        column.Spacing(10);

                        column.Item().Text(
                            $"Prescription ID: {prescription.PrescriptionId}");

                        column.Item().Text(
                            $"Date: {prescription.CreatedAt:dd MMM yyyy}");

                        column.Item().Text("DOCTOR DETAILS")
                            .Bold();

                        column.Item().Text(
                            $"Name: {prescription.DoctorName}");

                        column.Item().Text(
                            $"Qualification: {prescription.Qualification}");

                        column.Item().Text(
                            $"License: {prescription.LicenseNumber}");

                        column.Item().LineHorizontal(1);

                        column.Item().Text("PATIENT DETAILS")
                            .Bold();

                        column.Item().Text(
                            $"Name: {prescription.PatientName}");

                       

                        column.Item().LineHorizontal(1);

                        column.Item().Text("PRESCRIBED MEDICINES")
                            .Bold()
                            .FontSize(14);

                        column.Item().Table(table =>
                        {
                            table.ColumnsDefinition(columns =>
                            {
                                columns.RelativeColumn(2);
                                columns.RelativeColumn(1);
                                columns.RelativeColumn(1);
                                columns.RelativeColumn(1);
                                columns.RelativeColumn(2);
                            });

                            table.Header(header =>
                            {
                                header.Cell().Element(CellStyle)
                                    .Text("Medicine");

                                header.Cell().Element(CellStyle)
                                    .Text("Dosage");

                                header.Cell().Element(CellStyle)
                                    .Text("Frequency");

                                header.Cell().Element(CellStyle)
                                    .Text("Duration");

                                header.Cell().Element(CellStyle)
                                    .Text("Instructions");
                            });

                            foreach (var medicine in prescription.Items)
                            {
                                table.Cell().Element(CellStyle)
                                    .Text(medicine.MedicineName);

                                table.Cell().Element(CellStyle)
                                    .Text(medicine.Dosage);

                                table.Cell().Element(CellStyle)
                                    .Text(medicine.Frequency);

                                table.Cell().Element(CellStyle)
                                    .Text(medicine.Duration);

                                table.Cell().Element(CellStyle)
                                    .Text(medicine.Instructions);
                            }
                        });
                    });

                page.Footer()
                    .AlignCenter()
                    .Text("Generated by CareBridge")
                    .FontSize(9);
            });
        }).GeneratePdf();
    }

    private static IContainer CellStyle(IContainer container)
    {
        return container
            .Border(1)
            .BorderColor(Colors.Grey.Lighten2)
            .Padding(5);
    }
}